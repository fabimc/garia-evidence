import { createRequire } from "module";
const require = createRequire("/home/user/garia/.agent/skills/verify-garia/helpers/package.json");
const { chromium } = require("playwright");
const EV = "/home/user/garia/.agent/skills/verify-garia/evidence/keyboard-journey";
const b = await chromium.connectOverCDP("http://127.0.0.1:9222");
const page = b.contexts()[0].pages()[0];
await page.setViewportSize({ width: 1100, height: 700 });
await page.goto("http://127.0.0.1:8765/?platform=linux");
await page.waitForFunction(() => document.querySelector("#conn-text")?.textContent.includes("aria2 ·"));
await page.waitForSelector("#download-list [role=option]");
const rows = () => page.$$eval("#download-list [role=option]:not(.hidden)", (els) => els.filter(e => e.offsetParent).map((e) => ({ gid: e.dataset.gid, status: e.dataset.status, name: e.querySelector(".dl-name, .name")?.textContent?.trim() })));
const log = [];
page.on("request", (r) => { if (r.url().includes("6800")) { const d = r.postData() || ""; if (d.includes("remove")) log.push(d); } });
// Delete a queued row
await page.click('#filter-bar .nav-item:has-text("Queued")');
await page.waitForTimeout(400);
const before = await rows();
console.log("queued before", JSON.stringify(before));
const first = page.locator("#download-list [role=option]:visible").first();
await first.focus();
await page.keyboard.press("ArrowDown");
await page.keyboard.press("Control+Delete");
await page.waitForFunction(() => document.activeElement?.id === "confirm-cancel");
console.log("focused:", await page.evaluate(() => document.activeElement.id));
await page.keyboard.press("Tab");
console.log("focused:", await page.evaluate(() => document.activeElement.id));
await page.keyboard.press("Enter");
await page.waitForTimeout(1500);
const after = await rows();
const banner = await page.$eval("#notice-banner", (e) => ({ hidden: e.classList.contains("hidden") || !e.offsetParent, text: e.textContent.trim() })).catch(() => "no banner el");
console.log("queued after", JSON.stringify(after), "banner", JSON.stringify(banner));
console.log("rpc", log.map(l => l.slice(0, 300)).join("\n"));
await page.screenshot({ path: `${EV}/keyboard-delete.png` });
const fs = await import("fs");
fs.writeFileSync(`${EV}/keyboard-delete.rows.json`, JSON.stringify({ before, after, banner }, null, 2));
fs.writeFileSync(`${EV}/keyboard-delete.aria.txt`, await page.locator("body").ariaSnapshot());
// Help scroll in in-app sheet, short window
await page.setViewportSize({ width: 900, height: 480 });
await page.evaluate(() => document.documentElement.classList.add("in-app"));
await page.locator("#download-list [role=option]:visible").first().focus().catch(() => {});
await page.keyboard.press("Control+Shift+Slash");
await page.waitForSelector("#help-overlay:not(.hidden)");
const m1 = await page.$eval("#help-overlay .help-body", (e) => ({ scrollH: e.scrollHeight, clientH: e.clientHeight, overflow: getComputedStyle(e).overflowY }));
await page.$eval("#help-overlay .help-body", (e) => { const dt = [...e.querySelectorAll("dt")].find(d => d.textContent.includes("Keyboard-only")); dt.scrollIntoView({ block: "start" }); });
const m2 = await page.$eval("#help-overlay .help-body", (e) => {
  const dt = [...e.querySelectorAll("dt")].find(d => d.textContent.includes("Keyboard-only"));
  const r = dt.getBoundingClientRect(), br = e.getBoundingClientRect();
  return { scrollTop: e.scrollTop, visible: r.bottom > br.top && r.top < br.bottom, dtTop: r.top, bodyTop: br.top, bodyBottom: br.bottom, text: dt.nextElementSibling.textContent.replace(/\s+/g, " ").trim(), cmd: /⌘/.test(e.textContent), footerVisible: document.querySelector("#help-overlay .modal-footer")?.getBoundingClientRect().bottom <= innerHeight };
});
console.log("help", JSON.stringify(m1), JSON.stringify(m2));
await page.screenshot({ path: `${EV}/help-scroll.png` });
fs.writeFileSync(`${EV}/help-scroll.rows.json`, JSON.stringify({ viewport: { width: 900, height: 480 }, before: m1, after: m2 }, null, 2));
fs.writeFileSync(`${EV}/help-scroll.aria.txt`, await page.locator("#help-overlay").ariaSnapshot());
await b.close();
